def _simple_tactical_description(
    *,
    feint_id: str,
    display_name: str,
    ui_label: str,
    short_description: str,
    long_description: str,
    use: str,
    hit: str,
    crit: str,
    miss: str = "но {source} не успевает довести удар до цели",
    dodge: str = "но {target} уходит с линии",
    parry: str = "но {target} сбивает атаку",
    block: str = "но {target} принимает удар на защиту",
) -> CombatDescriptionDTO:
    event_texts = CombatEventTextSetDTO(
        use=[use],
        hit=[hit],
        crit=[crit],
        miss=[miss],
        dodge=[dodge],
        parry=[parry],
        block=[block],
    )
    return build_combat_description(
        resource_type="feints",
        resource_id=feint_id,
        icon=f"combat/feints/{feint_id}.svg",
        display_name=display_name,
        ui_label=ui_label,
        short_description=short_description,
        humanoid_long_description=long_description,
        humanoid_event_texts=event_texts,
        beast_event_texts=event_texts,
    )


